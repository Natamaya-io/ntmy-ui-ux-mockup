function url(string $path = ''): string {
    return BASE_URL . '/' . ltrim($path, '/');
}

function asset(string $path): string {
    return ASSET_PATH . '/' . ltrim($path, '/');
}

function e(?string $str): string {
    return htmlspecialchars((string) $str, ENT_QUOTES, 'UTF-8');
}

/**
 * Ambil URL gambar fitur layanan.
 * Return null kalau file tidak ada → view fallback ke ikon.
 */
function service_image(string $slug, string $file): ?string {
    if ($file === '') return null;
    $path = ROOT_PATH . '/assets/images/services/' . $slug . '/' . $file;
    if (file_exists($path)) {
        return ASSET_PATH . '/images/services/' . $slug . '/' . $file;
    }
    return null;
}

/**
 * Ambil URL gambar hero layanan.
 */
function service_hero_image(string $slug, string $file): ?string {
    if ($file === '') return null;
    $path = ROOT_PATH . '/assets/images/services/' . $slug . '/hero/' . $file;
    if (file_exists($path)) {
        return ASSET_PATH . '/images/services/' . $slug . '/hero/' . $file;
    }
    return null;
}

